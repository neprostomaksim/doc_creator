import type { Block } from './template-types';

const FORMAT_SPEC = `Структура документа — это JSON-объект вида {"blocks": [...]}. Допустимые блоки:
- {"type":"title","text":"..."} — заголовок документа
- {"type":"heading","number":"1","text":"НАЗВАНИЕ РАЗДЕЛА"} — раздел
- {"type":"clause","number":"1.1","text":"..."} — пункт
- {"type":"paragraph","text":"..."} — обычный абзац
- {"type":"list","items":["...","..."]} — список
- {"type":"table","rows":[["...","..."],["...","..."]]} — таблица

Правила ответа:
- Верни СТРОГО валидный JSON-объект {"blocks":[...]} без пояснений и без markdown-обёртки.
- Нумерацию пунктов сохраняй согласованной.
- Пиши на русском, в деловом юридическом стиле.`;

/** Промпт для режима assisted: точечная правка ГОТОВОГО договора с реальными данными. */
export function buildEditPrompt(
  blocks: Block[],
  instruction: string,
  materials: { name: string; content: string }[] = [],
): string {
  const materialsText = materials.length
    ? `\nМатериалы, на которые нужно опираться при правке (используй их содержимое там, где просит пользователь):\n${materials
        .map((m) => `--- ${m.name} ---\n${m.content}`)
        .join('\n\n')}\n`
    : '';

  return `Ты — помощник юриста, который редактирует готовый договор. В документе уже стоят реальные данные — их нельзя терять.

${FORMAT_SPEC}

Обязательные правила правки:
- Сохрани ВСЕ конкретные данные ровно так, как в исходнике: названия сторон, ФИО, УНП/ИНН, адреса, банковские реквизиты, номер и дату договора, суммы, сроки, проценты.
- НИКОГДА не вставляй плейсхолдеры вида {{...}} и не заменяй ими реальный текст. Не обезличивай документ.
- Ничего не выдумывай. Меняй ТОЛЬКО то, о чём просит пользователь; весь остальной текст переноси дословно.
${materialsText}
Текущая структура договора:
${JSON.stringify({ blocks }, null, 2)}

Задача пользователя: ${instruction}

Верни ПОЛНУЮ обновлённую структуру целиком, с сохранением всех данных.`;
}

/** Промпт для режима generative: сборка структуры договора с нуля. */
export function buildGeneratePrompt(params: {
  description: string;
  examples: string[];
  materials: { name: string; content: string }[];
}): string {
  const examplesText = params.examples.length
    ? `Примеры договоров пользователя (ориентируйся на их стиль и структуру):\n${params.examples
        .map((e, i) => `--- Пример ${i + 1} ---\n${e}`)
        .join('\n\n')}`
    : 'Примеры не предоставлены — используй типовую структуру договора.';

  const materialsText = params.materials.length
    ? `Материалы, которые нужно учесть в договоре:\n${params.materials
        .map((m) => `--- ${m.name} ---\n${m.content}`)
        .join('\n\n')}`
    : 'Дополнительные материалы не предоставлены.';

  return `Ты — помощник юриста, который составляет договор с нуля.

${FORMAT_SPEC}

${examplesText}

${materialsText}

Что нужно составить: ${params.description}

Собери полную структуру договора: заголовок, разделы с нумерацией, пункты, при необходимости списки и таблицы. Не придумывай конкретные реквизиты сторон, суммы и даты, если их нет во входных данных — оставляй общие формулировки. Верни СТРОГО валидный JSON-объект {"blocks":[...]}.`;
}

/**
 * Промпт авторазметки: ИИ находит в шаблоне места для подстановки данных и
 * привязывает их к реквизитам сторон, датам, суммам и т.п. Возвращает список
 * полей со ссылкой на фрагмент (unit_id) и точной подстрокой (text).
 */
export function buildAutoMarkupPrompt(params: {
  units: { unit_id: string; text: string }[];
  orgRequisites: { field_key: string; field_label: string }[];
  clientRequisites: { field_key: string; field_label: string }[];
}): string {
  const orgList = params.orgRequisites.length
    ? params.orgRequisites.map((r) => `${r.field_key} — ${r.field_label}`).join('\n')
    : '(список пуст)';
  const clientList = params.clientRequisites.length
    ? params.clientRequisites.map((r) => `${r.field_key} — ${r.field_label}`).join('\n')
    : '(список пуст)';

  return `Ты размечаешь шаблон договора: находишь конкретные места, которые при создании нового договора нужно заменять данными. Это реквизиты сторон (название/ФИО, ИНН, УНП, ОГРН, адрес, расчётный счёт, банк, БИК), номер и дата договора, город, суммы денег, сроки.

Тебе дан документ как список фрагментов текста (unit_id и text). Верни СТРОГО валидный JSON-объект без пояснений и без markdown-обёртки, вида:
{"fields":[
  {"unit_id":"...", "text":"точная подстрока из фрагмента", "name":"Короткое название поля", "source_type":"org_requisite|client_requisite|manual", "field_key":"inn или null", "input_type":"text|number|date|amount или null"}
]}

Правила:
- text — ТОЧНАЯ подстрока из соответствующего фрагмента, копируй символ в символ (именно то значение, которое будет меняться, без окружающих слов вроде «ИНН:»).
- source_type = "org_requisite", если это реквизит вашей стороны (Исполнитель/Продавец), "client_requisite" — реквизит другой стороны (Заказчик/Покупатель/Клиент), иначе "manual".
- field_key: для org_requisite и client_requisite подбери подходящий ключ из списков ниже; если подходящего нет — верни null и поставь source_type "manual".
- input_type: только для manual — "date" для дат, "amount" для денежных сумм, "number" для прочих чисел, "text" для остального. Для реквизитов — null.
- Не размечай названия разделов, служебные слова и общий текст пунктов — только конкретные подставляемые значения.
- Если сомневаешься, к какой стороне относится реквизит, используй "manual".

Реквизиты вашей организации (field_key — подпись):
${orgList}

Реквизиты клиента (field_key — подпись):
${clientList}

Документ (фрагменты):
${JSON.stringify(params.units)}`;
}

/**
 * Промпт извлечения реквизитов организации из текста загруженного документа
 * (договор, карточка предприятия). Возвращает список пар «поле → значение».
 */
export function buildExtractRequisitesPrompt(text: string): string {
  return `Извлеки из документа реквизиты ОДНОЙ организации (или ИП/физлица). Если в документе несколько сторон — бери первую (Исполнитель / Продавец / первую упомянутую).

Верни СТРОГО валидный JSON-объект без пояснений и markdown-обёртки, вида:
{"requisites":[{"label":"Название поля","value":"значение"}]}

Правила:
- label — короткое русское название поля (например: «Название», «УНП», «ИНН», «ОГРН», «Юридический адрес», «Расчётный счёт», «Банк», «БИК», «Директор», «Действует на основании»).
- value — точное значение из документа.
- Бери только реально присутствующие в тексте данные, ничего не выдумывай.
- Если поля нет — просто не включай его.

Текст документа:
${text.slice(0, 12000)}`;
}

/**
 * Промпт правок через ОПЕРАЦИИ над исходным документом (для сохранения
 * форматирования). ИИ возвращает точечные replace/insert_after/delete, а не
 * пересобирает документ. documentText — абзацы исходного .docx (по строкам).
 */
export function buildPatchPrompt(params: {
  documentText: string;
  instruction: string;
  materials?: { name: string; content: string }[];
  clientRequisites?: { field_label: string; field_value: string }[];
  orgRequisites?: { field_label: string; field_value: string }[];
}): string {
  const mat = params.materials?.length
    ? `\nМатериалы (используй их содержимое, если это требуется правкой):\n${params.materials
        .map((m) => `--- ${m.name} ---\n${m.content}`)
        .join('\n\n')}\n`
    : '';

  const reqBlock = (title: string, list?: { field_label: string; field_value: string }[]) =>
    list && list.length
      ? `\n${title}:\n${list.map((r) => `- ${r.field_label}: ${r.field_value}`).join('\n')}\n`
      : '';

  return `Ты редактируешь готовый договор точечными правками, не трогая остальной текст и оформление. Верни СТРОГО валидный JSON без пояснений и markdown-обёртки, вида:
{"edits":[
  {"op":"replace","find":"точный фрагмент из документа","replace":"на что заменить"},
  {"op":"insert_after","anchor":"точный фрагмент абзаца, после которого вставить","text":"текст нового абзаца"},
  {"op":"delete","find":"точный фрагмент абзаца, который удалить"}
]}

Правила:
- find/anchor — ТОЧНЫЕ подстроки из текста документа ниже, символ в символ (можно короткие, но однозначные).
- Для replace бери минимальный фрагмент, который меняется (например, только дату или только название стороны, без окружающих слов).
- Если нужно подставить реквизиты стороны — сделай отдельный replace для каждого значения (название, УНП/ИНН, ФИО директора, адрес, счёт и т.д.), заменяя старые данные на новые из списков реквизитов ниже.
- Не дублируй правки, не меняй то, о чём не просили. Нумерацию пунктов не трогай — она проставится сама.
- Даты держи согласованными. Если меняешь дату, от которой зависят другие сроки (окончание, поддержка, оплата, отчётность), пересчитай и их — отдельными replace. Если в документе несколько связанных дат одного события (например, несколько дат оказания услуг), и правка их затрагивает — приведи весь набор к непротиворечивому виду: ни одна дата не должна быть раньше даты договора и не должна противоречить остальным.
- Не выдумывай новые даты без основания: меняй только то, что следует из запроса пользователя и из логической связи с изменяемой датой.
${reqBlock('Реквизиты вашей стороны (Исполнитель)', params.orgRequisites)}${reqBlock('Реквизиты клиента (Заказчик), которые нужно подставить', params.clientRequisites)}${mat}
Что нужно сделать: ${params.instruction}

Текст документа (по абзацам):
${params.documentText}`;
}
